"""Investigation report rendering.

Produces two artefacts from a ranked incident:

* **Markdown** — a human-readable investigation with a suspect table, timeline
  strip, and per-suspect rationale, ready to paste into a postmortem doc.
* **JSON** — a machine-readable investigation for downstream automation.
"""

from __future__ import annotations

import json
from typing import Dict, List

from .graph import CausalGraph
from .model import Incident, Suspect
from .timeline import build_timeline, timeline_text


def render_json(incident: Incident, graph: CausalGraph,
                suspects: List[Suspect]) -> str:
    timeline = build_timeline(graph)
    payload = {
        "incident": {
            "id": incident.id,
            "title": incident.title,
            "origin_ts": incident.origin_ts,
            "summary": incident.summary,
            "node_count": graph.order(),
            "edge_count": graph.size(),
        },
        "primary_suspect": suspects[0].node_id if suspects else None,
        "suspects": [s.to_dict() for s in suspects],
        "timeline": [
            {
                "node_id": e.node_id,
                "t_start": e.t_start,
                "t_end": e.t_end,
                "status": e.status,
                "kind": e.kind,
            }
            for e in timeline
        ],
        "warnings": graph.validate(),
    }
    return json.dumps(payload, indent=2)


def render_markdown(incident: Incident, graph: CausalGraph,
                    suspects: List[Suspect]) -> str:
    lines: List[str] = []
    lines.append(f"# Investigation: {incident.title}")
    lines.append("")
    lines.append(f"- **Incident ID:** `{incident.id}`")
    if incident.origin_ts:
        lines.append(f"- **Origin:** {incident.origin_ts}")
    lines.append(f"- **Nodes:** {graph.order()}  **Edges:** {graph.size()}")
    if suspects:
        lines.append(f"- **Primary suspect:** `{suspects[0].node_id}` "
                     f"(score {suspects[0].score:.3f})")
    lines.append("")
    if incident.summary:
        lines.append("## Summary")
        lines.append("")
        lines.append(incident.summary)
        lines.append("")

    lines.append("## Ranked suspects")
    lines.append("")
    lines.append("| Rank | Node | Score | Blame | ErrW | Radius |")
    lines.append("| ---: | :--- | ----: | ----: | ---: | -----: |")
    for i, s in enumerate(suspects, start=1):
        lines.append(
            f"| {i} | `{s.node_id}` | {s.score:.3f} | {s.blame:.3f} "
            f"| {s.error_weight:.2f} | {s.blast_radius} |"
        )
    lines.append("")

    lines.append("## Why these suspects")
    lines.append("")
    for s in suspects[: min(5, len(suspects))]:
        lines.append(f"### `{s.node_id}`")
        for reason in s.rationale:
            lines.append(f"- {reason}")
        lines.append("")

    lines.append("## Timeline")
    lines.append("")
    lines.append("```")
    lines.append(timeline_text(build_timeline(graph)))
    lines.append("```")
    lines.append("")

    warnings = graph.validate()
    if warnings:
        lines.append("## Structural notes")
        lines.append("")
        for w in warnings:
            lines.append(f"- {w}")
        lines.append("")

    lines.append("---")
    lines.append("_Generated by CausalForge._")
    return "\n".join(lines) + "\n"
